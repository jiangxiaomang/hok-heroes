def table(headers, rows, cls=""):
    th = "".join(f"<th>{c}</th>" for c in headers)
    body = "".join("<tr>" + "".join(f'<td class="{c[0] if isinstance(c,tuple) else ""}">{c[1] if isinstance(c,tuple) else c}</td>' for c in r) + "</tr>" for r in rows)
    return f'<div class="tbl-wrap"><table class="{cls}"><tr>{th}</tr>{body}</table></div>'

